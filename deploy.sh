#!/usr/bin/env bash
# ==============================================================================
#  PlayDisplay — деплой сайта на боевой хостинг timeweb одной командой.
#
#  Запуск:   ./deploy.sh "текст коммита"
#            ./deploy.sh --dry-run          # ничего не менять, только показать
#            ./deploy.sh --yes "..."        # не спрашивать про удаления на сервере
#            ./deploy.sh --no-backup "..."  # без резервного пуша на GitHub
#
#  Что делает, по шагам:
#    1. снимает залипшие .git/*.lock (главная причина «коммит не проходит»);
#    2. проверяет, что рабочая копия на ветке hybrid-v8, и НЕ переключает ветку;
#    3. показывает незакоммиченные правки и коммитит их по именам файлов
#       (никогда `git add -A` — так в коммит попадает работа соседнего чата);
#    4. заливает site/ на timeweb через rsync — только изменившееся, минуя GitHub;
#    5. дописывает отчёт в DEPLOY-LOG.md;
#    6. по желанию пушит hybrid-v8 на GitHub как резерв (не блокирует деплой).
#
#  Правила общей папки — см. ПРАВИЛА-РАБОТЫ.md. Скрипт написан так, чтобы
#  их не нарушать: ветку не трогает, gh-pages не пересобирает, широких
#  удалений на диске не делает.
# ==============================================================================

set -uo pipefail

# ------------------------------------------------------------------ настройки --
SSH_USER="pdisplay"
SSH_HOST="vh432.timeweb.ru"
REMOTE_PATH="wordpress_2/public_html"     # относительно домашней папки на сервере
WORK_BRANCH="hybrid-v8"
SITE_URL="https://playdisplay.com"

# Локальный конфиг для переопределения любого из значений выше.
# Файл в .gitignore, в репозиторий не уезжает.
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# deploy.conf лежит в основной папке проекта и в git не хранится. При запуске из
# отдельного worktree его там нет — поэтому сначала ищем в основной копии, а потом
# рядом со скриптом (чтобы worktree мог при желании переопределить). Иначе пришлось бы
# копировать конфиг в каждый worktree и держать настройки в двух местах.
MAIN_REPO="$(dirname "$(git -C "$REPO" rev-parse --git-common-dir 2>/dev/null || echo "$REPO/.git")")"
case "$MAIN_REPO" in /*) ;; *) MAIN_REPO="$REPO/$MAIN_REPO" ;; esac
# Из самой основной папки git отдаёт «.git», и путь получается вида «…/repo/.» —
# строка не совпадает с $REPO, и конфиг прочитался бы дважды. Приводим к канону.
MAIN_REPO="$(cd "$MAIN_REPO" 2>/dev/null && pwd || echo "$REPO")"
[ -f "$MAIN_REPO/deploy.conf" ] && . "$MAIN_REPO/deploy.conf"
[ "$MAIN_REPO" != "$REPO" ] && [ -f "$REPO/deploy.conf" ] && . "$REPO/deploy.conf"

TARGET="$SSH_USER@$SSH_HOST"
LOG="$REPO/DEPLOY-LOG.md"
# Хеш последнего задеплоенного коммита. Путь берём у самого git, а не как "$REPO/.git":
# в отдельном worktree .git — это ФАЙЛ со ссылкой на настоящий каталог, и запись в него
# падала с «Not a directory». Деплой при этом продолжался, но следующий запуск не знал,
# что уже уехало. А деплоить из worktree удобно: рабочая копия может стоять на игровой
# ветке, пока сайт заливается с hybrid-v8.
GITDIR="$(git rev-parse --git-dir 2>/dev/null || echo "$REPO/.git")"
STATE="$GITDIR/pd-last-deploy"

# --------------------------------------------------------------------- разбор --
DRY=0
IGNORE_BUSY=0
NO_SMOKE=0
BACKUP=1
YES=0
MSG=""
for arg in "$@"; do
  case "$arg" in
    --dry-run|-n) DRY=1 ;;
    --ignore-busy) IGNORE_BUSY=1 ;;   # начинать, даже если на сервере идёт чужой rsync
    --no-smoke)   NO_SMOKE=1 ;;       # не запускать smoke.py перед поставкой
    --no-backup)  BACKUP=0 ;;
    --yes|-y)     YES=1 ;;
    -h|--help)    sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *)            MSG="$arg" ;;
  esac
done

# ----------------------------------------------------------------- оформление --
bold=$(tput bold 2>/dev/null || true); dim=$(tput dim 2>/dev/null || true)
red=$(tput setaf 1 2>/dev/null || true); grn=$(tput setaf 2 2>/dev/null || true)
ylw=$(tput setaf 3 2>/dev/null || true); off=$(tput sgr0 2>/dev/null || true)

step() { printf "\n%s▸ %s%s\n" "$bold" "$1" "$off"; }
ok()   { printf "  %s✓%s %s\n" "$grn" "$off" "$1"; }
warn() { printf "  %s!%s %s\n" "$ylw" "$off" "$1"; }
die()  { printf "\n  %s✗ %s%s\n\n" "$red" "$1" "$off" >&2; exit 1; }

cd "$REPO" || die "не нахожу папку проекта"

# Проверка rsync до всякой работы. На свежих macOS системный rsync заменён на
# openrsync, который не знает --itemize-changes, --filter и --chmod. Выяснять это
# посреди заливки на боевой сервер — плохая идея, поэтому пробуем флаги на пустых
# папках заранее.
# Путь к rsync можно задать в deploy.conf строкой RSYNC_BIN="/opt/homebrew/bin/rsync",
# но обычно это не нужно: если системный не подошёл, перебираем места, куда его ставит
# homebrew — /opt/homebrew на Apple Silicon и /usr/local на Intel. Заставлять человека
# править конфиг из-за подмены системной утилиты — лишний шаг на пути к деплою.
check_rsync() {
  command -v "$1" >/dev/null || return 1
  a="/tmp/pd-rsync-a-$$"; b="/tmp/pd-rsync-b-$$"
  mkdir -p "$a" "$b"
  "$1" -rltzc --omit-dir-times --chmod=D755,F644 --delete --itemize-changes \
        --filter='-s .DS_Store' --dry-run "$a/" "$b/" >/dev/null 2>&1
  rc=$?
  rm -rf "$a" "$b"
  return $rc
}

pick_rsync() {
  # Если путь задан руками — уважаем его и молча не подменяем.
  if [ -n "${RSYNC_BIN:-}" ]; then return 0; fi
  for cand in rsync /opt/homebrew/bin/rsync /usr/local/bin/rsync; do
    if check_rsync "$cand"; then
      RSYNC_BIN="$cand"
      return 0
    fi
  done
  RSYNC_BIN="rsync"     # ни один не подошёл — оставим системный, дальше будет внятная ошибка
  return 1
}

printf "%s\n%s  PlayDisplay → %s%s\n%s\n" \
  "════════════════════════════════════════════" "$bold" "$SITE_URL" "$off" \
  "════════════════════════════════════════════"
[ "$DRY" = 1 ] && warn "холостой прогон: ничего не изменится ни в git, ни на сервере"

# ══ 1. Залипшие локи ═══════════════════════════════════════════════════════════
step "Проверяю замки git"
FREED=0
for L in .git/index.lock .git/HEAD.lock .git/objects/maintenance.lock \
         .git/refs/heads/"$WORK_BRANCH".lock; do
  if [ -e "$L" ]; then
    # Лок моложе двух минут может принадлежать живому процессу — не трогаем.
    if [ -n "$(find "$L" -mmin +2 2>/dev/null)" ]; then
      FREED=1
      if [ "$DRY" = 0 ]; then
        rm -f "$L" && warn "снят залипший $L"
      else
        warn "залипший $L — будет снят при настоящем запуске"
      fi
    else
      die "$L создан только что — возможно, работает другой чат. Подожди минуту и повтори."
    fi
  fi
done
[ "$FREED" = 0 ] && ok "замков нет"

# ══ 2. Ветка ══════════════════════════════════════════════════════════════════
step "Проверяю ветку"
BRANCH=$(git rev-parse --abbrev-ref HEAD) || die "это не git-репозиторий"
# Фигурные скобки обязательны: bash 3.2 на macOS не разбирает многобайтные символы
# в именах переменных, и в «$BRANCH» кавычка-ёлочка прилипает к имени — получается
# несуществующая переменная, а с set -u это падение. В bash 5 работает и так.
[ "$BRANCH" = "$WORK_BRANCH" ] || die "рабочая копия на «${BRANCH}», а работа идёт в «${WORK_BRANCH}».
     Ветку я не переключаю (правило 1) — сделай это сам и проверь, что ничего не потерялось:
       git status && git switch $WORK_BRANCH"
ok "$BRANCH"

# ══ 3. Незакоммиченные правки ═════════════════════════════════════════════════
step "Штампую версии на файлы конструктора"
# ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ РУКАМИ. Статику на timeweb отдаёт nginx напрямую и ставит свой
# cache-control на год (замер записан в site/.htaccess). Браузер, один раз открывший
# страницу, год держит старый css — 17.08.2026 из-за этого страница компреда открылась
# «съехавшей»: вёрстка целая, а стилей нет, потому что доехал старый components.css.
# Скрипт дописывает ?v=<хеш содержимого> ссылкам на kit/css и kit/js, поэтому изменившийся
# файл получает новый адрес. Ручной ступенью это держать нельзя: её однажды забудут.
if [ -f site/kit/stamp.py ]; then
  python3 site/kit/stamp.py | sed 's/^/  /' || warn "штамп версий не прошёл — стили могут доехать из кэша"
else
  warn "site/kit/stamp.py не найден — версии на файлах конструктора не обновлены"
fi

# ---------------------------------------------------------------- смоук --
# Проверка ПЕРЕД коммитом и заливкой: смысл в том, чтобы остановить поставку, а не
# рассказать о поломке после неё. Ключ --no-smoke оставлен для случая, когда чинишь
# сам смоук или надо срочно поставить заплатку, зная о красном.
if [ -f "$REPO/smoke.py" ] && [ "$NO_SMOKE" = 0 ]; then
  step "Смоук-проверка сайта"
  if SMOKE=$(cd "$REPO" && python3 smoke.py 2>&1); then
    printf '%s\n' "$SMOKE" | tail -1 | sed 's/^/  /'
  else
    printf '%s\n' "$SMOKE" | sed 's/^/  /'
    die "смоук-проверка не прошла — деплой отменён.
     Починить и запустить снова, либо ./deploy.sh --no-smoke, если знаешь, что делаешь."
  fi
fi

step "Смотрю, что не закоммичено"
# bash 3.2 на macOS не знает mapfile — читаем в массив вручную.
DIRTY=()
while IFS= read -r line; do
  [ -n "$line" ] && DIRTY+=("$line")
done < <(git status --porcelain)

if [ ${#DIRTY[@]} -eq 0 ]; then
  ok "рабочая копия чистая"
else
  printf "  найдено %s изменений:\n" "${#DIRTY[@]}"
  printf "    %s\n" "${DIRTY[@]}"

  # Файлы вне site/ и вне документации — чужая территория либо мусор.
  SUSPECT=()
  for line in "${DIRTY[@]}"; do
    f="${line:3}"; f="${f%\"}"; f="${f#\"}"
    case "$f" in
      site/*|*.md|deploy.sh|deploy.conf|build_seo.py|smoke.py|.gitignore) ;;
      *) SUSPECT+=("$f") ;;
    esac
  done
  if [ ${#SUSPECT[@]} -gt 0 ]; then
    printf "\n"
    warn "вне site/ и документации — коммитить не буду, разберись сначала:"
    printf "    %s\n" "${SUSPECT[@]}"
  fi

  if [ "$DRY" = 0 ]; then
    if [ -z "$MSG" ]; then
      if [ -t 0 ]; then
        printf "\n  %sТекст коммита%s (пусто = не коммитить, залить как есть): " "$bold" "$off"
        read -r MSG
      else
        warn "текст коммита не задан и спросить некого — коммит пропускаю"
      fi
    fi
    if [ -n "$MSG" ]; then
      # Добавляем по именам: только site/ и документацию, поштучно.
      ADDED=0
      for line in "${DIRTY[@]}"; do
        f="${line:3}"; f="${f%\"}"; f="${f#\"}"
        case "$f" in
          site/*|*.md|deploy.sh|build_seo.py|smoke.py|.gitignore)
            git add -- "$f" && ADDED=$((ADDED+1)) ;;
        esac
      done
      if [ "$ADDED" -gt 0 ]; then
        git commit -q -m "$MSG" || die "коммит не прошёл"
        ok "закоммичено файлов: $ADDED — $(git rev-parse --short HEAD)"
      else
        warn "нечего коммитить в своей территории"
      fi
    else
      warn "коммит пропущен — на сервер уедет текущее состояние диска"
    fi
  fi
fi

HEAD_SHA=$(git rev-parse --short HEAD)
LAST=$(cat "$STATE" 2>/dev/null || true)

# ══ 4. Заливка на хостинг ═════════════════════════════════════════════════════
step "Заливаю site/ на $SSH_HOST"
[ -d "$REPO/site" ] || die "нет папки site/ — заливать нечего"

pick_rsync || die "ни один rsync на этой машине не понимает нужные флаги.
     Проверены: rsync из PATH, /opt/homebrew/bin/rsync, /usr/local/bin/rsync.
     На свежих macOS системный rsync подменён на openrsync, который не знает
     --itemize-changes, --filter и --chmod. Лечится одной командой:
       brew install rsync
     После установки просто запустите деплой снова — путь найдётся сам.
     Если homebrew ставит в необычное место, добавьте в deploy.conf строку:
       RSYNC_BIN=\"\$(brew --prefix)/bin/rsync\""
RSYNC_VER=$("$RSYNC_BIN" --version 2>/dev/null | head -1 | tr -s ' ' | cut -d' ' -f1-3)
ok "rsync подходящий: $RSYNC_VER${RSYNC_BIN:+ ($RSYNC_BIN)}"

# Что на сервере обязано выжить и никогда не удаляется:
#   old/        — статичный слепок старого вордпресса, 244 МБ, живёт только на сервере
#   .git/       — прежний git-клон; не нужен, но убирать его вручную и осознанно
#   .well-known — подтверждение SSL-сертификата
#   api/config.php, api/sessions/, api/outbox/ — ключи и рабочие данные ассистента
#   api/scene-settings.json — подобранный вид 3D-сцены, сохранённый «для всех» из панели
#   api/certs/  — корневой сертификат НУЦ Минцифры для GigaChat. Ставится на сервер один
#                 раз руками и в git не хранится. Если бы папка не была исключена, деплой
#                 с машины, где сертификат не скачан, УДАЛИЛ бы его на сервере — и ассистент
#                 молча перестал бы получать ответы модели.
#   В api/sessions/ лежит ещё и .guard-secret — секрет подписи задач стража. Его потеря
#   обнулила бы все выданные задачи, поэтому папка защищена целиком.
EXCLUDES=(
  # «-s» = правило только для отправляющей стороны: мусор macOS с Мака не уезжает,
  # но на сервере рука не связана. Обычный --exclude тут был ошибкой: он защищает
  # .DS_Store и на сервере тоже, а папка с ним внутри считается непустой и не
  # удаляется. Проверено: так на сервере навсегда остались бы огрызки _ARCHIVE.
  --filter='-s .DS_Store'
  --exclude='/old/'
  # /layer/ — чужой выложенный на сервер Next.js-экспорт (появился 27.08.2026,
  # 5 МБ, живёт по адресу playdisplay.com/layer/). В репозитории его нет, и без
  # этой строки rsync предлагал его снести на каждой поставке. Не наша территория:
  # кто выкладывал — тот и убирает. Появится в site/ — строку снять.
  --exclude='/layer/'
  # …и его серверные бэкапы вида /layer-backup-pre-v015-…/: их делает тот же чужой
  # процесс при своих выкладках. 29.08.2026 деплой сайта предлагал снести свежий
  # утренний бэкап целиком — логика та же, что у /layer/: не наша территория.
  --exclude='/layer-backup-*'
  # Внутри /ai-pack/ на сервере живёт ЧУЖОЙ Next.js-экспорт (team/, materials/,
  # _next/ — прототип соседнего чата, замечен 29.08.2026). Наш статичный
  # index.html едет как обычно, а их подпапки не трогаем: кто выкладывал —
  # тот и убирает. Переедут в site/ — строки снять.
  --exclude='/ai-pack/_next/'
  --exclude='/ai-pack/team/'
  --exclude='/ai-pack/materials/'
  --exclude='/.git/'
  --exclude='/.well-known/'
  --exclude='/api/config.php'
  --exclude='/api/sessions/'
  # Архивы на сервер не возим. digital.zip на 2,9 МБ приехал именно так:
  # он лежит в site/, в .gitignore есть *.zip — но rsync про gitignore
  # не знает, и файл спокойно уехал в веб-корень, откуда его мог скачать
  # любой. Правилом в .htaccess это не закрыть: статику на timeweb отдаёт
  # nginx напрямую, до Apache запрос не доходит.
  --exclude='*.zip'
  --exclude='*.tar'
  --exclude='*.tar.gz'
  --exclude='*.tgz'
  --exclude='*.rar'
  --exclude='*.7z'
  --exclude='/api/outbox/'
  --exclude='/api/certs/'
  # Настройки 3D-сцены, сохранённые «для всех» из секретной панели на самом сайте.
  # Файл рождается НА СЕРВЕРЕ (его пишет api/scene.php), в git его нет — без этой строки
  # первый же деплой снёс бы подобранный вид главной и вернул заводской.
  --exclude='/api/scene-settings.json'
  # Таблица рекордов мини-игры: тоже рождается на сервере (api/game.php), в git её нет
  --exclude='/api/game-scores.json'
  # ВРЕМЕННО (26.08.2026): живая диагностика превью соседнего чата, лежит только на
  # сервере ("удалить после проверки" — написано в самом файле). Обычный --exclude,
  # а не -s: файл надо ЗАЩИТИТЬ от удаления, а не просто не посылать. Когда проверка
  # закончится и файлы снимут с сервера, эти две строки удалить вместе с ними.
  --exclude='/tg-probe.php'
  --exclude='/tg-probe.log'
  # Приложенные посетителями файлы. Ждут отправки письма — деплой посреди чужого
  # разговора не должен уносить у человека уже загруженное ТЗ.
  --exclude='/api/uploads/'
  # Рабочее сырьё компреда: исходники картинок, модели 3D-гаража (37 МБ), Three.js и сама
  # страница гаража. Слайд с живой сценой из компреда убран 17.08.2026, страница на них не
  # ссылается; на диске оставлены (сцена может вернуться, готовить модели заново дорого).
  #
  # МОДИФИКАТОР «-s» ЗДЕСЬ ОБЯЗАТЕЛЕН, и это ровно та же грабля, что с .DS_Store выше.
  # Обычный --exclude защищает путь НА ОБЕИХ сторонах: файлы не уезжают, но и не удаляются
  # с сервера — один раз залитые 37 МБ остались бы там навсегда. Правило «только для
  # отправляющей стороны» означает «не посылать», и тогда --delete снимает их с сервера.
  --filter='-s /avtovaz/material/'
  --filter='-s /avtovaz/models/'
  --filter='-s /avtovaz/vendor/'
  --filter='-s /avtovaz/garage.html'
)

# Одно SSH-соединение на весь скрипт — пароль спросят один раз.
CTL="/tmp/pd-ssh-$$"
# ServerAliveInterval — не косметика: на заливке крупного файла канал молчит минутами,
# и NAT у провайдера или шаред-хостинг успевают закрыть его по бездействию. Тогда
# rsync висит навсегда и выглядит «застрявшим». Раз в 20 секунд посылаем «живой?»,
# после трёх пропусков соединение падает с ошибкой — падение лучше вечного ожидания.
SSH_OPTS=(-o ControlMaster=auto -o ControlPath="$CTL" -o ControlPersist=120
          -o ServerAliveInterval=20 -o ServerAliveCountMax=3)
cleanup() { ssh "${SSH_OPTS[@]}" -O exit "$TARGET" 2>/dev/null; rm -f "$CTL"; }
trap cleanup EXIT

ssh "${SSH_OPTS[@]}" -o ConnectTimeout=20 "$TARGET" true \
  || die "не подключиться к $TARGET — проверь SSH-доступ"
ok "соединение есть"

# ---------------------------------------------------------------- чужая заливка --
# Проверка появилась 24.08.2026 по факту: на сервере обнаружились ДВА процесса rsync
# по 22 минуты каждый — параллельные деплои из разных чатов. Оба с --delete, оба по
# одной и той же папке. Обошлось, но узнать об этом можно было только заглянув в ps
# руками, а deploy.sh спокойно запустил бы третий.
#
# Почему это опасно именно здесь: rsync заливает ДИСК, а не коммит, и в общей папке
# два чата видят один и тот же site/. Списки файлов совпадают, поэтому катастрофы
# обычно не выходит — но --delete во время чужой недоливки может снять файл, который
# сосед ещё не догрузил, а --partial оставит на сервере огрызок.
#
# Отказ, а не предупреждение: предупреждение в неинтерактивном запуске никто не
# прочитает. Escape-люк нужен, потому что процесс бывает и зависшим: rsync на
# оборванном соединении живёт до своего --timeout=180, а при мёртвом ssh и дольше.
# Скобки в "[r]sync" — чтобы grep не нашёл сам себя в списке процессов.
BUSY=$(ssh "${SSH_OPTS[@]}" "$TARGET" \
        'ps -eo pid,etime,args 2>/dev/null | grep "[r]sync --server" || true' 2>/dev/null)
if [ -n "$BUSY" ] && [ "$IGNORE_BUSY" = 0 ]; then
  printf "\n"
  warn "на сервере уже идёт заливка — свой деплой не начинаю:"
  printf '%s\n' "$BUSY" | sed 's/^/    /'
  die "подожди, пока сосед закончит, и запусти снова.
     Если процесс завис (время идёт, а файлы не меняются) — сними его на сервере:
       ssh $TARGET 'kill <pid>'
     Или запусти с --ignore-busy, если уверен, что мешать нечему."
fi
[ -n "$BUSY" ] && warn "чужая заливка идёт, но --ignore-busy велел не обращать внимания"

# -t  — сохранять время файлов, иначе rsync перезаливает всё при каждом запуске.
# -c  — сравнивать по контрольной сумме, а не по «размер + время с точностью до
#       секунды». Быстрая сверка молча пропускает правку, если файл не изменился
#       в размере и его правили в ту же секунду, что предыдущий деплой. Проверено:
#       так теряется правка. Лишние секунды на сверку дешевле потерянной правки.
# --partial — НЕ ВЫБРАСЫВАТЬ недокачанное. Проверено 20.08.2026 на первой заливке
#       hero-gameplay.mp4 (29 МБ): связь оборвалась на середине, и без этого флага
#       следующий запуск начинал файл с нуля. С ним rsync доливает остаток.
# --info=progress2 — общий прогресс одной строкой. Без него скрипт молчит, пока файл
#       не дойдёт целиком, и на тридцати мегабайтах это выглядит зависанием: владелец
#       ждал пять минут, глядя в неподвижное окно, и справедливо спросил «застряло?».
# --timeout=180 — оборванное соединение падает с ошибкой, а не висит бесконечно.
# Про -z: современный rsync сам не сжимает mp4, mp3, jpg, png и прочее уже сжатое
#       (свой список skip-compress), поэтому флаг тут ничего не стоит и остаётся.
RSYNC=("$RSYNC_BIN" -rltzc --omit-dir-times --chmod=D755,F644 --delete --itemize-changes
       --partial --info=progress2 --timeout=180
       "${EXCLUDES[@]}" -e "ssh ${SSH_OPTS[*]}" "$REPO/site/" "$TARGET:$REMOTE_PATH/")

# Сначала всегда холостой прогон: показать, что изменится и что удалится.
PLAN=$("${RSYNC[@]}" --dry-run --info=progress0 2>&1) || die "rsync не смог посмотреть сервер:
$PLAN"

# Разбор вывода --itemize-changes. Код изменения — ровно 11 символов, где первый
# символ это операция, а второй — тип объекта (f файл, d папка, L ссылка).
# Раньше здесь стоял грубый '^[<>ch]', и в список «отправлено» попадали
# предупреждения вида «cannot delete non-empty directory» — они тоже с «c».
ITEM='^[<>ch.][fdLDS]'
CHANGED=$(printf '%s\n' "$PLAN" | grep -cE "$ITEM" || true)
DELETED=$(printf '%s\n' "$PLAN" | grep -c '^\*deleting' || true)

# Всё, что не код изменения и не удаление — это жалобы rsync. Их надо видеть.
GRIPES=$(printf '%s\n' "$PLAN" | grep -vE "$ITEM" | grep -v '^\*deleting' \
         | grep -vE '^(sending|sent|total|$)' || true)
if [ -n "$GRIPES" ]; then
  printf "\n"
  warn "rsync жалуется:"
  printf '%s\n' "$GRIPES" | head -10 | sed 's/^/    /'
fi
printf "  к отправке: %s%s%s, к удалению на сервере: %s%s%s\n" \
  "$bold" "$CHANGED" "$off" "$bold" "$DELETED" "$off"

if [ "$DELETED" -gt 0 ]; then
  printf "\n"
  warn "будут удалены с сервера (их нет в site/):"
  printf '%s\n' "$PLAN" | grep '^\*deleting' | sed 's/^\*deleting  */    /' | head -30
  [ "$DELETED" -gt 30 ] && printf "    …и ещё %s\n" "$((DELETED-30))"
fi

if [ "$CHANGED" = 0 ] && [ "$DELETED" = 0 ]; then
  ok "сервер уже совпадает с site/ — заливать нечего"
  SENT_LIST=""
elif [ "$DRY" = 1 ]; then
  warn "холостой прогон — ничего не отправлено"
  SENT_LIST=$(printf '%s\n' "$PLAN" | grep -E "$ITEM" | cut -c13-)
else
  if [ "$DELETED" -gt 0 ] && [ "$YES" = 0 ]; then
    if [ -t 0 ]; then
      printf "\n  %sУдалить перечисленное и залить?%s [y/N] " "$bold" "$off"
      read -r a; [[ "$a" =~ ^[Yy]$ ]] || die "отменено, на сервере ничего не тронуто"
    else
      die "на сервере есть что удалять, а подтвердить некому.
     Посмотри список глазами: ./deploy.sh --dry-run
     Согласен — добавь --yes"
    fi
  fi
  # ВЫВОД ИДЁТ И НА ЭКРАН, И В ФАЙЛ. Раньше здесь стояло OUT=$("${RSYNC[@]}" 2>&1), то
  # есть вывод целиком уходил в переменную — и никакие флаги прогресса в окно попасть не
  # могли ни при каких настройках. На килобайтах текста это было незаметно, а на первой
  # заливке 33 МБ медиа окно молчало 21 минуту, и живая заливка выглядела зависанием.
  # tee — единственный способ получить и то и другое: rsync нельзя запустить «ещё раз,
  # но уже для показа». Код возврата берём у ПЕРВОГО звена конвейера (PIPESTATUS), иначе
  # получим успех tee вместо настоящего итога rsync.
  OUT_FILE=$(mktemp -t pd-rsync)
  "${RSYNC[@]}" 2>&1 | tee "$OUT_FILE"
  RC=${PIPESTATUS[0]}
  OUT=$(cat "$OUT_FILE")
  rm -f "$OUT_FILE"
  [ "$RC" -eq 0 ] || die "rsync упал:
$OUT"
  SENT_LIST=$(printf '%s\n' "$OUT" | grep -E "$ITEM" | cut -c13-)
  LEFT=$(printf '%s\n' "$OUT" | grep -c 'cannot delete' || true)
  [ "$LEFT" -gt 0 ] && warn "папок не удалось убрать: $LEFT — внутри осталось что-то,
    чего rsync не трогает. Посмотри список выше."
  ok "залито, сайт обновлён: $SITE_URL"
fi

# ══ 5. Журнал ═════════════════════════════════════════════════════════════════
step "Пишу в DEPLOY-LOG.md"
if [ "$DRY" = 1 ]; then
  warn "холостой прогон — журнал не тронут"
else
  if [ -n "$LAST" ]; then
    COMMITS=$(git log --oneline "$LAST..HEAD" 2>/dev/null)
  else
    COMMITS=$(git log --oneline -5)
  fi
  [ -z "$COMMITS" ] && COMMITS="(новых коммитов нет — залито текущее состояние)"

  # Список файлов в журнале подрезаем: одна поставка бывает и на 364 файла,
  # а при чистке сервера — на тысячу. Полный перечень такой длины журнал топит.
  SENT_SHOWN=""
  if [ -n "$SENT_LIST" ]; then
    N_SENT=$(printf '%s\n' "$SENT_LIST" | wc -l | tr -d ' ')
    SENT_SHOWN=$(printf '%s\n' "$SENT_LIST" | head -40)
    [ "$N_SENT" -gt 40 ] && SENT_SHOWN="$SENT_SHOWN
…и ещё $((N_SENT-40))"
  fi

  ENTRY="## $(date '+%Y-%m-%d %H:%M') — $WORK_BRANCH @ $HEAD_SHA

**Коммиты в этой поставке**
\`\`\`
$COMMITS
\`\`\`

**На сервер отправлено файлов:** $CHANGED, удалено: $DELETED
$( [ -n "$SENT_SHOWN" ] && printf '```\n%s\n```' "$SENT_SHOWN" )
"
  # Новая запись встаёт сразу под маркером, то есть выше всех предыдущих.
  MARK="<!-- НОВЫЕ ЗАПИСИ ДОБАВЛЯЮТСЯ ПОД ЭТОЙ СТРОКОЙ. НЕ УДАЛЯТЬ. -->"
  if [ -f "$LOG" ] && grep -qF "$MARK" "$LOG"; then
    N=$(grep -nF "$MARK" "$LOG" | head -1 | cut -d: -f1)
    { head -n "$N" "$LOG"; printf '\n%s\n' "$ENTRY"; tail -n +"$((N+1))" "$LOG"; } \
      > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
  else
    # Журнала нет или маркер потеряли — создаём заново.
    printf '# Журнал деплоя\n\nЗаписи пишет `deploy.sh`, новые сверху.\n\n%s\n\n%s\n' \
      "$MARK" "$ENTRY" > "$LOG"
  fi
  echo "$HEAD_SHA" > "$STATE"
  git add -- DEPLOY-LOG.md && git commit -q -m "Журнал деплоя: $HEAD_SHA" 2>/dev/null \
    && ok "запись добавлена и закоммичена" || ok "запись добавлена"
fi

# ══ 6. Резерв на GitHub ═══════════════════════════════════════════════════════
if [ "$BACKUP" = 1 ] && [ "$DRY" = 0 ]; then
  step "Резервный пуш на GitHub"
  if git push -q origin "$WORK_BRANCH" 2>/dev/null; then
    ok "$WORK_BRANCH запушена в резерв"
  else
    warn "пуш не прошёл (нет кредов или сети) — на сайт это не влияет, история осталась локально"
  fi
fi

