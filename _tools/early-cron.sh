#!/bin/sh
# Еженедельный разбор ранних сигналов. Задача Cron в панели timeweb:
# «Ранние сигналы», Сценарий SH, путь /home/p/pdisplay/early-cron.sh.
#
# ПОЧЕМУ РАЗ В НЕДЕЛЮ, А НЕ КАЖДЫЙ ДЕНЬ. Дайджест закупок (tenders-cron.sh)
# ходит ежедневно: извещения появляются и закрываются за дни. Здесь другое —
# планы-графики меняются медленно, между позицией плана и извещением проходят
# месяцы. Ежедневное письмо по ним было бы шумом, который перестанут читать,
# а вместе с ним перестанут читать и ежедневный дайджест.
#
# Прогон долгий: на каждый найденный план приходится отдельная страница
# позиций на четверть мегабайта, и первый боевой запуск 18.09.2026 занял
# около четырёх минут. Поэтому время выбрано не рядом с ежедневным дайджестом
# (13:30), чтобы два скрипта не стучались в ЕИС одновременно.
#
# Письмо идёт через sendmail хостинга, а не через почтовый слой сайта:
# у сайта свой конфиг, и он уже был однажды настроен «складывать в папку».
HOME_DIR="/home/p/pdisplay"
/usr/bin/python3 "$HOME_DIR/early.py" \
  --mail "a.sudarikov@playdisplay.ru" \
  >> "$HOME_DIR/early-weekly.log" 2>&1
tail -n 3000 "$HOME_DIR/early-weekly.log" > "$HOME_DIR/early-weekly.log.tmp" 2>/dev/null \
  && mv "$HOME_DIR/early-weekly.log.tmp" "$HOME_DIR/early-weekly.log"
