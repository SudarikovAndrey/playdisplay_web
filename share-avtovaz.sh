```

Открыть `http://localhost:8000/avtovaz/`. Пароля локально нет, на боевом он есть.

Файлом `avtovaz/private/page.html` страницу открывать нельзя — придёт без стилей: пути к
css считаются от текущей папки и уезжают на уровень глубже.

## Что правим

| Можно | Нельзя |
|---|---|
| `avtovaz/private/page.html` — сама презентация | `kit/` — конструктор: он общий, приезжает из основного репозитория |
| `avtovaz/assets/` — картинки страницы | `avtovaz/index.php` — проверка пароля |
| `avtovaz/material/` — сырьё, из которого режем кадры | |

Если понадобился новый блок или правка в ките — скажите, я внесу их в основном
