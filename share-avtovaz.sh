## Устройство страницы

Презентация — РЕЖИМ СЛАЙДОВ: у `<html>` класс `deck`, прокрутка прилипает, один слайд =
один экран (`.slide` + `.slide-shell`). Оформление — тема `kit/css/theme-street.css`
(«асфальт и картон»), под мир игры.

**Бюджет высоты слайда — не весь экран.** У `.slide` свои отступы: на 1440×900 это 144 px,
то есть содержимому остаётся 756. Сверять высоту `.slide-shell` надо с `innerHeight`
МИНУС отступы. Слайд, который «влезает» по полному экрану, на деле уезжает вниз.

**Незаполненные цифры помечены блоком `blank`** — оранжевая черта на месте числа. Перед
отправкой партнёру ищите по странице `class="blank"`: это и есть список того, что осталось
подставить.

**Знака LADA в файлах нет** там, где стоит рамка «место под знак»: знак присылает владелец.

## Правила типографики (обязательные)

- **Никогда не длинное тире.** Только обычное короткое: `–`.
- **Никаких висячих союзов и предлогов в заголовках.** Одно- и двухбуквенные слова
  приклеиваются к следующему через `&nbsp;`.

## Прежде чем верстать новое

`kit/blocks.json` — опись 48 блоков. У каждого есть поле `traps`: это НЕ примечания, а
список того, что уже ломалось и почему сделано именно так. Читать до правок.
`kit/KIT.md` — та же память в прозе. Каталог живьём: `/kit/catalog.html` через `serve.py`.

## Что уже ломалось на этой странице

- **Лента отзывов.** Гасить края маской нельзя: маска стоит на месте, а карточки едут, и
  первая карточка растворялась при нулевой прокрутке. Гаснет сама карточка по доле своей
  обрезки краем ленты. Долю считать по `offsetLeft`/`offsetWidth`, а НЕ по
  `getBoundingClientRect`: у повёрнутой карточки экранная коробка уже настоящей, и замер
  начинает гоняться за собственным результатом — угол улетает в предел, колода дёргается.
- **Прилипание прокрутки** снимать и на тягу, и на свою анимацию, иначе браузер тянет
  ленту к ближайшей карточке посреди хода.
- **Порядок наложения карточек** задавать руками через `z-index`: у контейнера прокрутки
  `transform-style` принудительно плоский, трёхмерного пространства нет, и повёрнутая
  карточка рисуется поверх ровной просто потому, что стоит в разметке позже.
- **Кадр-предмет** (вырезанный объект на прозрачном фоне) выводится через `contain`, а не
  `cover`, и ширину ему надо задавать числом: у абсолютно позиционированной картинки
  `width: auto` не выводится из `left`/`right`.
- **Вырезы проверять на ТЁМНОЙ подложке.** На белом превью не видно ни остатка серой
  тени, ни дыры в кузове машины — обе ошибки так и прошли.
- **Кэш боевого сервера — год.** Статику отдаёт nginx напрямую, `max-age=31536000`.
  Поэтому ссылки на кит помечены `?v=<хеш>`; версии проставляет скрипт на стороне студии.

## Что осталось сделать

Это и есть фронт работы — с этого стоит начинать.

1. **Десять незаполненных цифр.** Поиск по странице: `class="blank"` — оранжевая черта на
   месте числа. Там метрики взаимодействия, доля владельцев LADA среди игроков, длительность
   сезона, сроки разработки. Числа даёт студия и АвтоВАЗ, но список держать под рукой.
2. **Кадры галереи «Тачки в игре» временные.** Стоят подходящие по смыслу картинки из
   игры; под каждый довод готовится своя картинка или короткий ролик. Заменять по одному,
   `object-position` подбирать замером, а не на глаз.
3. **Знака LADA в файлах нет** там, где стоит подписанная рамка «место под знак» — знак
   присылает владелец. Своим вариантом не заменять.
4. **Кадр телефона на первом экране** ждёт нарезку геймплея: сейчас там скриншот, тег
   меняется на `<video autoplay muted loop playsinline>`, стили у картинки и ролика одни.
5. **3D-сцены гаража в этой копии нет.** Слайд с ней убран, модели (37 МБ) остались на
   стороне студии. Если сцена понадобится — просить, а не собирать заново.

## Как проверять правки

**Замером, а не на глаз.** Половина ошибок на этой странице находилась только счётом:

- высота слайда — сверять `.slide-shell` с `innerHeight` МИНУС отступы `.slide`;
- вырезанные картинки смотреть НА ТЁМНОЙ ПОДЛОЖКЕ: на белом превью не видно ни остатка
  серой тени, ни дыры в кузове — обе ошибки так и прошли;
- горизонтальную прокрутку страницы проверять сравнением `scrollWidth` и `innerWidth`:
  вылет ленты за край экрана легко превращается в поехавший вбок документ;
- телефон проверять на 375–401 px по ширине: там ломались и заголовки, и плитки.

## Как отдавать работу

Своя ветка, говорящие русские сообщения коммитов, маленькие коммиты. `git add` по именам
файлов — никогда `git add -A`. Дальше pull request.
MD
}

# ── КОМАНДЫ ─────────────────────────────────────────────────────────────────
cmd_init() {
  step "Создаю репозиторий-спутник"
  [ -d "$SHARE_DIR/.git" ] && die "в $SHARE_DIR уже есть репозиторий"
  mkdir -p "$SHARE_DIR"
  rsync "${RSYNC_OPTS[@]}" "$ROOT/site/avtovaz/" "$SHARE_DIR/avtovaz/" || die "не скопировать компред"
  rsync "${RSYNC_OPTS[@]}" "$ROOT/site/kit/"     "$SHARE_DIR/kit/"     || die "не скопировать конструктор"
  ok "файлы на месте"
  write_helpers
  write_claude_md
  printf '__pycache__/\n.DS_Store\n' > "$SHARE_DIR/.gitignore"
  ok "serve.py, README.md, CLAUDE.md написаны"

  git -C "$SHARE_DIR" init -q -b main
  git -C "$SHARE_DIR" add -A
  git -C "$SHARE_DIR" commit -q -m "Компред LADA × Рынок Пацана: страница и конструктор для совместной работы"
  ok "первый коммит сделан"

  step "Осталось создать приватный репозиторий на GitHub"
  cat <<TXT
  Из папки спутника:
      cd "$SHARE_DIR"
      gh repo create $REPO_NAME --private --source=. --push

  Пригласить партнёра. Подкоманды add-collaborator у gh НЕТ (проверено на 2.92) —
  приглашение отправляется через api:
      gh api -X PUT repos/<ваш-ник>/$REPO_NAME/collaborators/<ник-партнёра> -f permission=push

  Дальше партнёру нужна одна команда:
      git clone https://github.com/<ваш-ник>/$REPO_NAME.git
TXT
}

cmd_push() {
  need_share
  step "Отправляю компред из основного репозитория в общий"
  D="$(dirty_here)"
  if [ -n "$D" ]; then
    warn "в основном репозитории есть незакоммиченные правки компреда:"
    printf "    %s\n" $D
    warn "они уедут в общий репозиторий как есть — это нормально, но сначала посмотри список"
  fi
  rsync "${RSYNC_OPTS[@]}" "$ROOT/site/avtovaz/" "$SHARE_DIR/avtovaz/"
  rsync "${RSYNC_OPTS[@]}" "$ROOT/site/kit/"     "$SHARE_DIR/kit/"
  write_helpers
  write_claude_md
  ok "файлы перенесены"
  if [ -z "$(git -C "$SHARE_DIR" status --porcelain)" ]; then
    ok "в общем репозитории и так всё свежее"
    return
  fi
  git -C "$SHARE_DIR" status --short | sed 's/^/    /'
  git -C "$SHARE_DIR" add -A
  git -C "$SHARE_DIR" commit -q -m "${1:-Обновление компреда со стороны студии}"
  ok "коммит сделан"
  git -C "$SHARE_DIR" push 2>/dev/null && ok "отправлено на GitHub" \
    || warn "push не прошёл — сделай его руками из $SHARE_DIR"
}

cmd_pull() {
  need_share
  step "Забираю правки партнёра в основной репозиторий"
  D="$(dirty_here)"
  if [ -n "$D" ]; then
    printf "\n"
    warn "СНАЧАЛА РАЗБЕРИСЬ С ЭТИМ. В основном репозитории есть незакоммиченные правки"
    warn "компреда — перенос их перетрёт, и восстановить будет нечем:"
    printf "    %s\n" $D
    die "закоммить или отмени их и повтори"
  fi
  git -C "$SHARE_DIR" pull --ff-only 2>/dev/null && ok "общий репозиторий обновлён" \
    || warn "pull не прошёл — обнови $SHARE_DIR руками"

  # Кит НЕ принимаем обратно: он общий, и правки партнёра в нём не должны просочиться
  # в остальные презентации студии незаметно. Если он там что-то менял — это видно в
  # pull request, и переносится вручную, осознанно.
  if ! git -C "$SHARE_DIR" diff --quiet HEAD -- kit 2>/dev/null; then :; fi
  # ПАПКУ material НЕ СИНХРОНИЗИРУЕМ НИ В ОДНУ СТОРОНУ, И ЭТО НЕ ПРЕДПОЧТЕНИЕ.
  # rsync --delete снимает всё, чего нет у источника. Владелец кладёт сырьё (присланные
  # картинки, кубик, варианты машин) прямо в site/avtovaz/material, у спутника его нет —
  # и КАЖДЫЙ pull молча стирал только что положенные файлы. Так пропали cube.png, Union.png
  # и папка niva; в git они не отслеживаются, восстановить было нечем. Сырьё принадлежит
  # той машине, на которой лежит, и переносить его между репозиториями незачем.
  rsync -a --delete --filter='-s .DS_Store' \
        --exclude='models/' --exclude='vendor/' --exclude='garage.html' --exclude='material/' \
        "$SHARE_DIR/avtovaz/" "$ROOT/site/avtovaz/"
  ok "компред перенесён"

  step "Что изменилось — посмотри до коммита"
  git -C "$ROOT" status --short -- site/avtovaz | sed 's/^/    /'
  cat <<'TXT'

  Дальше руками, чтобы ничего не уехало вслепую:
      git diff -- site/avtovaz          # прочитать правки
      python3 serve.py                  # посмотреть страницу
      git add -- site/avtovaz/...       # по именам файлов
      git commit -m "Правки партнёра: ..."
      ./deploy.sh "..."                 # если пора на сервер
TXT
}

cmd_status() {
  printf "  основной: %s\n" "$ROOT"
  printf "  спутник:  %s\n" "$SHARE_DIR"
  [ -d "$SHARE_DIR/.git" ] || { warn "спутника ещё нет"; return; }
  printf "\n"
  bold "Общий репозиторий"
  git -C "$SHARE_DIR" log --oneline -3 | sed 's/^/    /'
  R="$(git -C "$SHARE_DIR" status --porcelain)"
  [ -n "$R" ] && { warn "незакоммиченное:"; printf "    %s\n" $R; } || ok "чисто"
  printf "\n"
  bold "Расхождение с основным (что перенесёт push)"
  diff -rq --exclude=.git --exclude=models --exclude=vendor --exclude=garage.html \
       --exclude=.DS_Store --exclude=__pycache__ \
       "$ROOT/site/avtovaz" "$SHARE_DIR/avtovaz" 2>/dev/null | sed 's/^/    /' || true
}

case "${1:-}" in
  init)   cmd_init ;;
  push)   cmd_push "${2:-}" ;;
  pull)   cmd_pull ;;
  status) cmd_status ;;
  *) sed -n '2,32p' "$0" | sed 's/^# \{0,1\}//' ;;
esac
