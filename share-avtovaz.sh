#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# КОМПРЕД ДЛЯ ПАРАЛЛЕЛЬНОЙ РАБОТЫ С ПАРТНЁРОМ
#
# Что это. Отдельный маленький репозиторий, в котором лежит ТОЛЬКО компред АвтоВАЗу и
# конструктор страниц. Партнёр клонирует его, работает у себя (тоже через Claude),
# смотрит на своём localhost и присылает правки через pull request. Основной сайт,
# ассистент, кейсы и вся история playdisplay_web ему при этом не видны.
#
# ПОЧЕМУ НЕ ВЕТКА В ОСНОВНОМ РЕПОЗИТОРИИ: ветка даёт доступ ко всему репозиторию целиком,
# включая историю, ключи в прошлых коммитах и чужие территории. Отдельный репозиторий
# отдаёт ровно то, над чем идёт совместная работа.
#
# ПОЧЕМУ НЕ git subtree: он умеет отображать ОДНУ папку. Компреду нужны две — сама
# страница и конструктор, — и они лежат в разных местах. Поэтому перенос делает rsync,
# а сведение правок берёт на себя git внутри общего репозитория.
#
# ГЛАВНОЕ ПРАВИЛО, ЧТОБЫ НЕ ПОТЕРЯТЬ ЧУЖУЮ РАБОТУ.
#   Пока идёт совместная работа, компред правится В ОБЩЕМ РЕПОЗИТОРИИ — и партнёром,
#   и вами. Основной репозиторий на это время только принимает результат и деплоит.
#   Тогда сведение правок делает git, а не rsync, и ничего не перетирается молча.
#   Если всё же понадобилось поправить компред здесь — сначала `push`, потом правки там.
#
# КОМАНДЫ
#   ./share-avtovaz.sh init    — создать репозиторий-спутник и приватный репо на GitHub
#   ./share-avtovaz.sh push    — отправить состояние из основного репозитория в общий
#   ./share-avtovaz.sh pull    — забрать правки партнёра в основной репозиторий
#   ./share-avtovaz.sh status  — что где лежит и что расходится
#
# Адрес папки-спутника можно задать переменной SHARE_DIR, по умолчанию — рядом с проектом.
# ═══════════════════════════════════════════════════════════════════════════════
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHARE_DIR="${SHARE_DIR:-$ROOT/../playdisplay-avtovaz}"
REPO_NAME="${REPO_NAME:-playdisplay-avtovaz}"

bold() { printf "\033[1m%s\033[0m\n" "$1"; }
ok()   { printf "  \033[32m✓\033[0m %s\n" "$1"; }
warn() { printf "  \033[33m!\033[0m %s\n" "$1"; }
die()  { printf "  \033[31m✗\033[0m %s\n" "$1"; exit 1; }
step() { printf "\n\033[1m%s\033[0m\n" "$1"; }

# Что уезжает партнёру. Модели 3D-гаража (37 МБ) и Three.js сюда НЕ входят: слайд со
# сценой из компреда убран, страница на них не ссылается, а репозиторий с ними стал бы
# в три раза тяжелее на пустом месте.
RSYNC_OPTS=(-a --delete
  --filter='-s .DS_Store'
  --exclude='models/'
  --exclude='vendor/'
  --exclude='garage.html'
  --exclude='__pycache__/'
  # Сырьё не ездит между репозиториями: см. объяснение у команды pull. Оно у каждого своё,
  # а --delete из чужого списка стирает только что положенные файлы.
  --exclude='material/'
)

need_share() { [ -d "$SHARE_DIR/.git" ] || die "нет репозитория-спутника в $SHARE_DIR — начни с ./share-avtovaz.sh init"; }

dirty_here() {
  # Незакоммиченное ВНУТРИ территории компреда. Именно оно потерялось бы при переносе.
  git -C "$ROOT" status --porcelain -- site/avtovaz site/kit | grep -v '^?? site/avtovaz/material/' || true
}

# ── СЛУЖЕБНЫЕ ФАЙЛЫ СПУТНИКА ────────────────────────────────────────────────
write_helpers() {
  cat > "$SHARE_DIR/serve.py" <<'PY'
#!/usr/bin/env python3
"""Локальный просмотр компреда: python3 serve.py → http://localhost:8000/avtovaz/

Компред лежит в avtovaz/private/page.html и на боевом отдаётся через avtovaz/index.php
после пароля. Открывать page.html файлом НЕЛЬЗЯ: пути к css и картинкам считаются от
текущей папки и уезжают на уровень глубже — страница придёт без стилей. Этот сервер
отдаёт её по адресу /avtovaz/, поэтому вёрстка выглядит ровно как на сервере.
"""
import http.server, os, socketserver, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 8000
PAGES = {'/avtovaz/': 'avtovaz/private/page.html',
         '/avtovaz/index.php': 'avtovaz/private/page.html'}


class Handler(http.server.SimpleHTTPRequestHandler):
    protocol_version = 'HTTP/1.1'

    def __init__(self, *a, **kw):
        super().__init__(*a, directory=ROOT, **kw)

    def end_headers(self):
        self.send_header('Cache-Control', 'no-store')
        super().end_headers()

    def send_head(self):
        clean = self.path.split('?', 1)[0]
        for pref in PAGES:
            if pref.endswith('/') and clean.startswith(pref + 'private/'):
                self.send_response(302)
                self.send_header('Location', pref)
                self.send_header('Content-Length', '0')
                self.end_headers()
                return None
        alt = PAGES.get(clean)
        if alt and os.path.isfile(os.path.join(ROOT, alt)):
            self.path = '/' + alt
        return super().send_head()


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


if __name__ == '__main__':
    print('http://localhost:%d/avtovaz/  (Ctrl+C — стоп)' % PORT)
    Server(('', PORT), Handler).serve_forever()
PY

  cat > "$SHARE_DIR/README.md" <<'MD'
# LADA × Рынок Пацана — компред

Закрытая презентация АвтоВАЗу. Здесь лежит только она и конструктор страниц, на котором
она собрана. Основной сайт студии — в другом репозитории.

## Посмотреть

```
