/* СЦЕНЫ ОБЛАКА ТОЧЕК ДЛЯ «ЦИФРОВОГО СЛОЯ».
 *
 * Движок — kit/js/trace.js. Здесь только содержание: какую форму облако принимает
 * на каждом экране. Формы задаются в долях рамки слайда (data-trace-box у секции),
 * поэтому одни и те же числа работают и на 2560, и на 390.
 *
 * Сквозной сюжет, ради которого всё это и сделано:
 *   01 путь короткий и упирается в пространство
 *   02 путь ОБРЫВАЕТСЯ, дальше только тусклая пыль
 *   03 те же точки ведут линию дальше, через четыре этапа
 *   09 одна линия превращается в сеть
 *   10 сеть тает, остаётся одна мысль
 */
(function () {
  'use strict';
  if (!window.kitTrace) return;

  var T = window.kitTrace, TAU = Math.PI * 2;

  /* ── 01 · ИДЕЯ ───────────────────────────────────────────────────────────
     Внизу — физическое пространство (сетка пола), сверху — цифровой слой
     (контур плоскости), между ними две связи. Путь пока короткий. */
  T.scene('s01', function () {
    return [
      { k: 'grid', x0: 0.02, y0: 0.62, x1: 0.98, y1: 1.00, cols: 9, rows: 4, role: 'space', weight: 2.2 },
      { k: 'rect', x0: 0.10, y0: 0.10, x1: 0.92, y1: 0.44, role: 'ghost', weight: 1.0 },
      { k: 'path', p: [[0.06, 0.86], [0.26, 0.80], [0.44, 0.74]], role: 'line', weight: 1.5, flow: 1 },
      { k: 'dot', x: 0.44, y: 0.74, r: 0.04, role: 'node', weight: 0.7 },
      { k: 'path', p: [[0.26, 0.80], [0.28, 0.44]], role: 'ghost', weight: 0.3, w: 0.005 },
      { k: 'path', p: [[0.44, 0.74], [0.49, 0.44]], role: 'ghost', weight: 0.3, w: 0.005 }
    ];
  });

  /* ── 02 · ПРОБЛЕМА ───────────────────────────────────────────────────────
     Тот же пол, тот же путь. Внутри пространства он насыщается (два сгустка),
     а после выхода ОБРЫВАЕТСЯ: дальше только рассеянная пыль без формы.
     Разрыв делает пустое место между концом линии и пылью — рисовать «обрыв»
     нечем, он и есть отсутствие точек. */
  T.scene('s02', function () {
    return [
      { k: 'grid', x0: 0.02, y0: 0.62, x1: 0.98, y1: 1.00, cols: 9, rows: 4, role: 'space', weight: 2.0 },
      { k: 'path', p: [[0.02, 0.88], [0.20, 0.82], [0.33, 0.73], [0.46, 0.66]], role: 'line', weight: 1.5, flow: 1 },
      { k: 'dot', x: 0.30, y: 0.75, r: 0.07, role: 'node', weight: 0.9 },
      { k: 'dot', x: 0.24, y: 0.62, r: 0.05, role: 'node', weight: 0.5 },
      { k: 'dot', x: 0.46, y: 0.66, r: 0.02, role: 'node', weight: 0.3 },
      { k: 'scatter', x0: 0.62, y0: 0.24, x1: 1.00, y1: 0.94, role: 'ghost', weight: 1.4 }
    ];
  });

  /* ── 03 · ПУТЬ ───────────────────────────────────────────────────────────
     Линия идёт через весь экран и проходит четыре узла. Волна бежит по всей
     длине — именно она читается как «путь продолжается», а не «нарисована». */
  T.scene('s03', function () {
    var p = [[0.01, 0.58], [0.20, 0.44], [0.42, 0.57], [0.64, 0.42], [0.86, 0.53], [0.99, 0.47]];
    return [
      { k: 'grid', x0: 0.02, y0: 0.74, x1: 0.98, y1: 1.00, cols: 12, rows: 3, role: 'space', weight: 1.1 },
      { k: 'path', p: p, role: 'line', weight: 2.4, flow: 1.4 },
      { k: 'dot', x: 0.20, y: 0.44, r: 0.035, role: 'node', weight: 0.5 },
      { k: 'dot', x: 0.42, y: 0.57, r: 0.035, role: 'node', weight: 0.5 },
      { k: 'dot', x: 0.64, y: 0.42, r: 0.035, role: 'node', weight: 0.5 },
      { k: 'dot', x: 0.86, y: 0.53, r: 0.035, role: 'node', weight: 0.5 }
    ];
  });

  /* ── 04 · ПРОСТРАНСТВО ───────────────────────────────────────────────────
     Пять узлов и обмен между ними. Волны пущены в РАЗНЫЕ стороны (flow со
     знаком): в одну сторону это выглядит конвейером, а не разговором. */
  T.scene('s04', function () {
    var n = [[0.12, 0.54], [0.34, 0.24], [0.56, 0.64], [0.78, 0.30], [0.94, 0.70]];
    var out = [], i;
    for (i = 0; i < n.length; i++) out.push({ k: 'dot', x: n[i][0], y: n[i][1], r: 0.045, role: 'node', weight: 0.55 });
    for (i = 0; i < n.length - 1; i++) {
      out.push({ k: 'path', p: [n[i], n[i + 1]], role: 'line', weight: 0.8, flow: i % 2 ? -1.1 : 1.1, w: 0.008 });
    }
    /* Возврат от данных к человеку: без него цепочка читается как труба, а не
       как круг, в котором опыт возвращается тому же человеку. */
    out.push({ k: 'path', p: [n[4], [0.62, 0.95], [0.26, 0.90], n[0]], role: 'ghost', weight: 0.9, flow: -0.8, w: 0.01 });
    return out;
  });

  /* ── 05 · ОНЛАЙН ─────────────────────────────────────────────────────────
     Слева физический павильон, справа его цифровая версия, между ними поток.
     Правая форма НЕ копия: она реже и чуть выше — иначе читается как две
     одинаковые коробки, а не как переход в другую среду. */
  T.scene('s05', function () {
    return [
      { k: 'rect', x0: 0.04, y0: 0.36, x1: 0.34, y1: 0.80, role: 'space', weight: 1.7 },
      { k: 'grid', x0: 0.06, y0: 0.38, x1: 0.32, y1: 0.78, cols: 5, rows: 4, role: 'space', weight: 0.9 },
      { k: 'rect', x0: 0.64, y0: 0.26, x1: 0.96, y1: 0.70, role: 'node', weight: 1.2 },
      { k: 'grid', x0: 0.66, y0: 0.28, x1: 0.94, y1: 0.68, cols: 4, rows: 3, role: 'ghost', weight: 0.5 },
      { k: 'path', p: [[0.34, 0.58], [0.50, 0.46], [0.64, 0.48]], role: 'line', weight: 1.2, flow: 1.6 }
    ];
  });

  /* ── 06 · ВОЗМОЖНОСТИ ────────────────────────────────────────────────────
     Ядро и лучи к подключаемым модулям. Кольцо здесь НЕ рисуем: настоящее
     кольцо стоит в разметке (.core-map), и второе, нарисованное по другой
     рамке, с ним не совпало бы — два почти одинаковых эллипса со сдвигом
     выглядят браком, а не глубиной. */
  T.scene('s06', function () {
    /* Сгустка в СЕРЕДИНЕ здесь нет намеренно: там стоит название ядра и строка под
       ним, и облако за буквами превращало их в кашу (поймано на показе). Середину
       занимает разметка, облаку остаются лучи. */
    var out = [];
    for (var i = 0; i < 10; i++) {
      var a = (i / 10) * TAU - Math.PI / 2;
      out.push({
        k: 'path',
        p: [[0.5 + Math.cos(a) * 0.20, 0.5 + Math.sin(a) * 0.20],
            [0.5 + Math.cos(a) * 0.46, 0.5 + Math.sin(a) * 0.46]],
        role: 'ghost', weight: 0.5, flow: 0.9, w: 0.006
      });
    }
    return out;
  });

  /* ── 07 · СЦЕНАРИИ ───────────────────────────────────────────────────────
     Одна точка входа, три исхода. Выбранный сценарий — светлая линия с волной,
     остальные остаются тенью: так видно, что система ОДНА и она перестраивается,
     а не что сценариев три. Вариант приходит из переключателя (событие kit:switch). */
  T.scene('s07', function (S) {
    var start = [0.04, 0.52];
    var ends = [[0.97, 0.20], [0.97, 0.52], [0.97, 0.84]];
    var mids = [[0.46, 0.26], [0.46, 0.50], [0.46, 0.78]];
    var out = [{ k: 'dot', x: start[0], y: start[1], r: 0.05, role: 'node', weight: 0.8 }];
    for (var i = 0; i < 3; i++) {
      var on = i === (S.v || 0);
      out.push({
        k: 'path', p: [start, mids[i], ends[i]],
        role: on ? 'line' : 'ghost',
        weight: on ? 2.0 : 0.55,
        flow: on ? 1.3 : 0,
        w: on ? 0.014 : 0.008
      });
      out.push({ k: 'dot', x: ends[i][0] - 0.03, y: ends[i][1], r: on ? 0.045 : 0.02, role: on ? 'node' : 'ghost', weight: on ? 0.5 : 0.15 });
    }
    return out;
  });

  /* ── 08 · РЕЗУЛЬТАТ ──────────────────────────────────────────────────────
     Слева столбики — «сколько пришло». Справа те же точки собираются в линию
     пути одного человека: у обычной аналитики есть высота, но нет направления. */
  T.scene('s08', function () {
    var out = [], h = [0.42, 0.62, 0.34, 0.74, 0.50], i;
    for (i = 0; i < h.length; i++) {
      var x = 0.05 + i * 0.065;
      out.push({ k: 'path', p: [[x, 0.86], [x, 0.86 - h[i] * 0.55]], role: 'space', weight: 0.42, w: 0.012 });
    }
    out.push({ k: 'path', p: [[0.46, 0.80], [0.60, 0.62], [0.74, 0.68], [0.88, 0.40], [0.98, 0.34]], role: 'line', weight: 2.0, flow: 1.2 });
    out.push({ k: 'dot', x: 0.60, y: 0.62, r: 0.03, role: 'node', weight: 0.35 });
    out.push({ k: 'dot', x: 0.88, y: 0.40, r: 0.03, role: 'node', weight: 0.35 });
    return out;
  });

  /* ── 09 · МАСШТАБ ────────────────────────────────────────────────────────
     Человек в середине, вокруг — области применения. Связи идут от середины,
     а не по кругу: это не сеть учреждений между собой, а один человек, у
     которого много возможных продолжений. */
  T.scene('s09', function () {
    var out = [{ k: 'dot', x: 0.5, y: 0.5, r: 0.05, role: 'node', weight: 0.9 }], i;
    for (i = 0; i < 12; i++) {
      var a = (i / 12) * TAU - Math.PI / 2;
      var x = 0.5 + Math.cos(a) * 0.42, y = 0.5 + Math.sin(a) * 0.40;
      out.push({ k: 'dot', x: x, y: y, r: 0.022, role: 'node', weight: 0.2 });
      out.push({ k: 'path', p: [[0.5, 0.5], [x, y]], role: 'ghost', weight: 0.3, flow: i % 3 === 0 ? 0.9 : 0, w: 0.006 });
    }
    return out;
  });

  /* ── 10 · ФИНАЛ ──────────────────────────────────────────────────────────
     Сеть распадается: остаётся одна короткая линия и еле различимая пыль по
     всему кадру. Точек столько же — они просто перестают складываться в форму. */
  T.scene('s10', function () {
    return [
      /* Линия ушла в правый нижний угол: посередине кадра стоит сам финальный текст,
         и полоса точек за буквами читалась как брак печати, а не как остаток пути. */
      { k: 'path', p: [[0.56, 0.90], [0.97, 0.86]], role: 'line', weight: 0.8, flow: 0.7 },
      { k: 'scatter', x0: 0.00, y0: 0.00, x1: 1.00, y1: 1.00, role: 'ghost', weight: 3.4 }
    ];
  });

  /* Переключатель сценариев говорит облаку, какую ветку подсветить. Связь идёт
     событием: переключатель про облако не знает, облако про переключатель тоже. */
  document.addEventListener('kit:switch', function (e) {
    if (e.detail && e.detail.id === 's07') T.variant('s07', e.detail.index);
  });

  T.start();
})();
