#!/bin/zsh
# Пересобрать POEMIQ из gold-proto и положить на сайт в site/poemiq/.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. На сайте лежит СНИМОК, а не живая сборка: правки в
# gold-proto сами до /poemiq/ не доезжают. Один раз это делается руками за пять
# минут, на третий раз забывается один шаг — и на боевом висит вчерашняя версия.
#
# Порядок ровно такой, и он не случаен:
#   1. build.py вшивает в разметку base64-ом ВСЁ — модели колец, HDR-окружения,
#      пять фотографий и ролик логотипа. Поэтому переносить нужно ОДИН файл, а
#      папки models/ и product/ на сайт не копируются вовсе.
#   2. Шапка-пояснение дописывается СКРИПТОМ, а не живёт в исходнике: build.py
#      перезаписывает index.html целиком, и вручную вставленный комментарий
#      пропал бы на первой же пересборке.
#
# Деплой скрипт НЕ запускает — это отдельное решение: ./deploy.sh "…"
set -e
cd "$(dirname "$0")"
SRC=gold-proto
DST=site/poemiq/index.html

[ -f "$SRC/build.py" ] || { echo "  ✗ нет $SRC/build.py — проект не на месте"; exit 1; }

echo "▸ Собираю POEMIQ из $SRC"
( cd "$SRC" && /usr/bin/python3 build.py )

was=""
[ -f "$DST" ] && was=$(tail -n +15 "$DST" | md5 -q)
now=$(md5 -q "$SRC/index.html")

mkdir -p site/poemiq
{
cat <<'HEAD'
<!-- POEMIQ — витрина ювелирного бренда. ЭТО СНИМОК СБОРКИ, не живая страница.
     Источник: gold-proto/ в корне репозитория (свой CLAUDE.md и README.md там же).
     Пересобрать и обновить: ./sync-poemiq.sh, затем ./deploy.sh "что сделали".

     ОДИН ФАЙЛ И БОЛЬШЕ НИЧЕГО. build.py вшивает сюда base64-ом модели колец,
     HDR-окружения, пять фотографий и ролик логотипа — отсюда 10 МБ (5 МБ в
     сжатом виде). Локальных ссылок на файлы у страницы нет, копировать models/
     и product/ на сайт не нужно.

     ЧТО ОНА ТЯНЕТ СНАРУЖИ, и это стоит поправить отдельной правкой:
     three@0.168 и meshoptimizer@0.21 с cdn.jsdelivr.net, шрифты с
     fonts.googleapis.com. Расходится с правилом «site/ самодостаточен» и делает
     страницу заложником чужой сети — тем самым, из-за чего сайт вставал в Азии.
     Исходник для правки — gold-proto/template.html. -->
HEAD
cat "$SRC/index.html"
} > "$DST"

printf "  размер: %.1f МБ\n" "$(( $(wc -c < "$DST") ))e-6"
if [ "$was" = "$now" ]; then
  echo "  ✓ страница не изменилась — на сайте уже была эта сборка"
else
  echo "  ✓ страница ОБНОВЛЕНА (была $was, стала $now)"
  echo "    не забудьте: ./deploy.sh \"POEMIQ: что изменилось\""
fi
